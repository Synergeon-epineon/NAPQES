# ---------------------------------------------------------------------------
# v8 KAT vectors (tests/kat/v8_vectors.json, generated by gen_kats_v8.py)
#
# v8 encryption is deterministic in (primes, sk, aad, message) — the nonce is
# a synthetic IV — so these vectors pin the *public* API byte-for-byte and are
# the reference corpus every other language implementation must reproduce.
# They exist because the v7 corpus above does not exercise v8 at all, which is
# how the Rust port's missing domain-0x0B format subkey went undetected
# (docs/CAVEATS.md, V3-CVF1 Residual 4).
# ---------------------------------------------------------------------------

_V8_VECTORS_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "kat", "v8_vectors.json"
)


def _load_v8_vectors():
    with open(_V8_VECTORS_PATH, encoding="utf-8") as f:
        return json.load(f)["vectors"]


_V8_ALL = _load_v8_vectors()
_V8_POSITIVE = [v for v in _V8_ALL if v["kind"] == "positive"]
_V8_NEGATIVE = [v for v in _V8_ALL if v["kind"] == "negative"]


@pytest.mark.parametrize("vec", _V8_POSITIVE, ids=[v["id"] for v in _V8_POSITIVE])
def test_v8_positive_encrypt_deterministic(vec):
    """encrypt_bytes_v8 must reproduce the stored ciphertext byte-for-byte."""
    ct = napqes.encrypt_bytes_v8(
        vec["message"],
        vec["key"],
        bytes.fromhex(vec["sk_hex"]),
        aad=bytes.fromhex(vec["aad_hex"]),
    )
    assert ct.hex() == vec["ciphertext_hex"], f"{vec['id']}: v8 ciphertext mismatch"


@pytest.mark.parametrize("vec", _V8_POSITIVE, ids=[v["id"] for v in _V8_POSITIVE])
def test_v8_positive_decrypt_roundtrip(vec):
    """decrypt_bytes_v8 must recover the plaintext from the stored ciphertext."""
    pt = napqes.decrypt_bytes_v8(
        bytes.fromhex(vec["ciphertext_hex"]),
        vec["key"],
        bytes.fromhex(vec["sk_hex"]),
        aad=bytes.fromhex(vec["aad_hex"]),
    )
    assert pt == vec["message"], f"{vec['id']}: v8 roundtrip mismatch"


@pytest.mark.parametrize("vec", _V8_NEGATIVE, ids=[v["id"] for v in _V8_NEGATIVE])
def test_v8_negative_raises(vec):
    """Tampered / mis-keyed v8 ciphertexts must raise ValueError."""
    with pytest.raises(ValueError, match=vec.get("expected_exception", "")):
        napqes.decrypt_bytes_v8(
            bytes.fromhex(vec["tampered_hex"]),
            vec["key"],
            bytes.fromhex(vec["sk_hex"]),
            aad=bytes.fromhex(vec["aad_hex"]),
        )


def test_v8_empty_message_is_not_empty_ciphertext():
    """The empty string must produce a full authenticated v8 ciphertext.

    An implementation that short-circuits ``message == ""`` to empty bytes
    emits an unauthenticated, trivially forgeable "ciphertext" and diverges
    from every other implementation; W001 pins the padded behaviour.
    """
    w001 = next(v for v in _V8_POSITIVE if v["id"] == "W001")
    assert w001["message"] == ""
    ct = bytes.fromhex(w001["ciphertext_hex"])
    assert len(ct) == 2928, f"Expected the 2928-byte v8 minimum, got {len(ct)}"


