@pytest.mark.parametrize("vec", _NEGATIVE, ids=[v["id"] for v in _NEGATIVE])
def test_negative_raises_value_error(vec):
    """Tampered / invalid ciphertexts must raise ValueError with expected message."""
    key = vec["key"]
    aad = bytes.fromhex(vec["aad_hex"])
    tampered = bytes.fromhex(vec["tampered_hex"])
    expected_msg = vec["expected_exception"]
    allow_legacy = vec.get("allow_legacy_unauthenticated", False)

    with pytest.raises(ValueError, match=expected_msg):
        napqes.decrypt_bytes(
            tampered, key, aad=aad,
            allow_legacy_unauthenticated=allow_legacy,
        )


